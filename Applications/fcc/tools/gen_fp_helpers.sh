#!/bin/sh
# Regenerate fp_helpers.h from fp_lib.c. Requires arm-none-eabi toolchain.
# Embedded helpers must be position-independent: no .rodata jump tables.
set -e
cd "$(dirname "$0")/.."
GCC=arm-none-eabi-gcc
LD=arm-none-eabi-ld
OBJCOPY=arm-none-eabi-objcopy
NM=arm-none-eabi-nm
TMP=${TMPDIR:-/tmp}/fcc-fp-$$
$GCC -mthumb -mcpu=cortex-m0plus -Os -fno-jump-tables -nostdlib \
     -ffreestanding -c fp_lib.c -o $TMP.o
$LD -Ttext=0 $TMP.o /usr/lib/gcc/arm-none-eabi/15/thumb/v6-m/nofp/libgcc.a \
    -o $TMP.elf 2>/dev/null
$OBJCOPY -O binary --only-section=.text $TMP.elf $TMP.bin
python3 - $TMP.bin $TMP.elf <<'PY'
import sys, subprocess, re
data = open(sys.argv[1], 'rb').read()
out = subprocess.check_output(['arm-none-eabi-nm', sys.argv[2]], text=True)
offs = {m.group(2): int(m.group(1),16)
        for m in re.finditer(r'^([0-9a-f]+) T (fp_\w+)$', out, re.M)}
names = sorted(offs, key=lambda n: offs[n])
f = open('fp_helpers.h','w')
f.write('/* Generated by tools/gen_fp_helpers.sh from fp_lib.c.\n')
f.write(' * GCC Runtime Library Exception applies to the linked libgcc code.\n')
f.write(' * Position-independent Thumb-1, no .rodata jump tables. */\n')
f.write('#ifndef FCC_FP_HELPERS_H\n#define FCC_FP_HELPERS_H\n\n')
f.write('static const unsigned char fp_helpers[] = {\n')
for i in range(0, len(data), 12):
    f.write('    ' + ','.join('0x%02x' % b for b in data[i:i+12]) + ',\n')
f.write('};\n#define FP_HELPERS_SIZE ((int)sizeof(fp_helpers))\n\n')
for n in names:
    f.write('#define FP_%s  0x%04x\n' % (n[3:].upper(), offs[n]))
f.write('\n#endif\n')
f.close()
print('fp_helpers.h:', len(data), 'bytes,', len(names), 'helpers')
PY
rm -f $TMP.o $TMP.elf $TMP.bin
